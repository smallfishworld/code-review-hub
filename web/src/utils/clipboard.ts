/**
 * Copy text to clipboard with an HTTP-intranet fallback.
 *
 * `navigator.clipboard` is undefined in non-HTTPS contexts other than
 * localhost (common on intranet deployments like http://10.x.x.x:3000),
 * so we fall back to a temporary off-screen textarea + execCommand('copy').
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fall through to legacy copy path
  }
  try {
    const el = document.createElement('textarea');
    el.value = text;
    el.setAttribute('readonly', '');
    el.style.position = 'fixed';
    el.style.opacity = '0';
    el.style.pointerEvents = 'none';
    document.body.appendChild(el);
    el.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(el);
    return ok;
  } catch {
    return false;
  }
}
